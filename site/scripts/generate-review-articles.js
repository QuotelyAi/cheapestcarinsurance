#!/usr/bin/env node

/**
 * Generate 90 Review Articles for Cheapest Car Insurance Tulsa
 * - Type A: Expand on existing content with unique perspectives
 * - Type C: Expert commentary and analysis updates
 * - Images: Different profile images + article images via Unsplash or API generation
 * - Uses Haiku model (via Claude API) for content generation
 */

const fs = require('fs');
const path = require('path');
const https = require('https');

// Configuration
const POSTS_FILE = path.join(__dirname, '../content/posts.json');
const OUTPUT_FILE = path.join(__dirname, '../content/review-articles.json');
const FIRST_REVIEW_DATE = new Date('2025-10-15T08:00:00Z');
const MAX_DAYS_BETWEEN = 7;

// Load existing posts
function loadPosts() {
  const data = fs.readFileSync(POSTS_FILE, 'utf8');
  return JSON.parse(data);
}

// Sort posts by date (oldest first)
function sortPostsByDate(posts) {
  return [...posts].sort((a, b) => new Date(a.date) - new Date(b.date));
}

// Generate publishing schedule
function generateSchedule(numArticles) {
  const schedule = [];
  let currentDate = new Date(FIRST_REVIEW_DATE);

  for (let i = 0; i < numArticles; i++) {
    schedule.push(new Date(currentDate));

    // Add random 1-7 days for next article (except for last)
    if (i < numArticles - 1) {
      const daysToAdd = Math.floor(Math.random() * MAX_DAYS_BETWEEN) + 1;
      currentDate = new Date(currentDate.getTime() + daysToAdd * 24 * 60 * 60 * 1000);
    }
  }

  return schedule;
}

