// Create review article content (to be generated via Claude API)
function createReviewArticleTemplate(originalPost, index, publishDate) {
  const reviewType = index % 2 === 0 ? 'expansion' : 'commentary';

  return {
    id: 1000 + index, // Unique ID for review articles
    title: generateReviewTitle(originalPost.title, reviewType),
    slug: generateReviewSlug(originalPost.slug, index),
    excerpt: `Expert review and analysis of ${originalPost.title}. Updated insights and expanded perspectives on this important insurance topic.`,
    content: `[PLACEHOLDER: Generated by Claude Haiku API]`, // Will be filled by API
    author: 'Insurance Review Team',
    date: publishDate.toISOString(),
    modified: publishDate.toISOString(),
    featured_media: null, // To be populated with Unsplash image ID
    status: 'publish',
    categories: originalPost.categories || [],
    tags: [...(originalPost.tags || []), 'expert-review', 'updated-analysis'],
    meta_description: `Expert review: ${originalPost.title}. Updated analysis and insights for Oklahoma drivers.`,
    meta_keywords: originalPost.meta_keywords || '',

    // Custom fields for review articles
    review_type: reviewType, // 'expansion' or 'commentary'
    original_post_id: originalPost.id,
    original_post_slug: originalPost.slug,
    profile_image_url: getRandomProfileImage(index),
    article_image_url: getArticleImage(index),
    reviewer_name: getReviewerName(index),
    reviewer_title: 'Insurance Expert'
  };
}

// Generate review article title
function generateReviewTitle(originalTitle, type) {
  if (type === 'expansion') {
    return `Expert Deep Dive: ${originalTitle}`;
  } else {
    return `2025 Update: ${originalTitle} - What's Changed`;
  }
}

// Generate unique slug for review article
function generateReviewSlug(originalSlug, index) {
  return `review-${index + 1}-${originalSlug}`;
}

// Get reviewer name (different for each review)
